class _MedicationCard extends StatelessWidget {
  final Medication medication;
  final VoidCallback onDelete;

  const _MedicationCard({
    required this.medication,
    required this.onDelete,
  });

  @override
  Widget build(BuildContext context) {
    return Card(
      elevation: AppTokens.elevationSm,
      child: Padding(
        padding: const EdgeInsets.all(AppTokens.space16),
        child: Column(
          crossAxisAlignment: CrossAxisAlignment.start,
          children: [
            Row(
              children: [
                Expanded(
                  child: Text(
                    medication.name,
                    style: AppTypography.h6,
                  ),
                ),
                IconButton(
                  icon: const Icon(Icons.delete_outline, size: AppTokens.iconSm),
                  color: AppColors.error,
                  onPressed: onDelete,
                ),
              ],
            ),
            const SizedBox(height: AppTokens.space8),
            _InfoChip(label: 'Dosage', value: medication.dosage),
            const SizedBox(height: AppTokens.space4),
            _InfoChip(label: 'Frequency', value: medication.frequency),
            const SizedBox(height: AppTokens.space4),
            _InfoChip(label: 'Duration', value: medication.duration),
            if (medication.instructions != null) ...[
              const SizedBox(height: AppTokens.space8),
              Container(
                padding: const EdgeInsets.all(AppTokens.space8),
                decoration: BoxDecoration(
                  color: AppColors.infoLight,
                  borderRadius: BorderRadius.circular(AppTokens.radiusXs),
                ),
                child: Row(
                  children: [
                    const Icon(
                      Icons.info_outline,
                      size: AppTokens.iconSm,
                      color: AppColors.info,
                    ),
                    const SizedBox(width: AppTokens.space8),
                    Expanded(
                      child: Text(
                        medication.instructions!,
                        style: AppTypography.bodySmall.copyWith(
                          color: AppColors.infoDark,
                        ),
                      ),
                    ),
                  ],
                ),
              ),
            ],
          ],
        ),
      ),
    );
  }
}

class _InfoChip extends StatelessWidget {
  final String label;
  final String value;

  const _InfoChip({required this.label, required this.value});

  @override
  Widget build(BuildContext context) {
    return Row(
      children: [
        Text(
          '$label: ',
          style: AppTypography.bodySmall.copyWith(
            color: AppColors.textSecondary,
          ),
        ),
        Text(
          value,
          style: AppTypography.bodySmall.copyWith(
            fontWeight: FontWeight.w600,
          ),
        ),
      ],
    );
  }
}